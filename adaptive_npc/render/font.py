GLYPHS = {c: tuple(r for r in rows.split("/")) for c, rows in _G.items()}
for _c, _rows in GLYPHS.items():
    assert len(_rows) == GLYPH_H and all(len(r) == GLYPH_W for r in _rows), _c

_cache = {}


def _glyph_surface(ch, color):
    key = (ch, color)
    surf = _cache.get(key)
    if surf is None:
        rows = GLYPHS.get(ch.upper(), GLYPHS["?"])
        surf = pygame.Surface((GLYPH_W, GLYPH_H), pygame.SRCALPHA)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    surf.set_at((x, y), color)
        _cache[key] = surf
    return surf


def text_width(text, scale=1):
    return max(0, len(text) * ADVANCE - 1) * scale


def draw_text(surface, text, x, y, color, scale=1, center=False, right=False, shadow=None):
    """Draw `text` with its top-left at (x, y); `center` / `right` treat x as the middle / right edge.
    `shadow` = colour of a 1-pixel (scaled) drop shadow."""
    color = tuple(color)
    w = text_width(text, scale)
    if center:
        x -= w // 2
    elif right:
        x -= w
    x, y = int(x), int(y)
    for dx, dy, col in (((scale, scale, tuple(shadow)),) if shadow else ()) + ((0, 0, color),):
        for i, ch in enumerate(text):
            g = _glyph_surface(ch, col)
            if scale != 1:
                g = pygame.transform.scale(g, (GLYPH_W * scale, GLYPH_H * scale))
            surface.blit(g, (x + dx + i * ADVANCE * scale, y + dy))
    return w
